package org.example.atividadeRevisaoSolid;

public class Atividade4 {

    //Explique quem pode acessar um atributo ou método declarado com cada modificador:
    //
    //a) private
    //b) default (sem modificador)
    //c) protected
    //d) public


    //a) private
    //Um atributo ou método private só pode ser acessado dentro da própria classe onde foi declarado.

    //b) default (sem modificador)
    //Quando nenhum modificador é informado, o acesso é do tipo default (ou package-private).
    //Uma classe filha só acessa default se estiver no mesmo package.

    //c) protected
    //Um membro protected pode ser acessado:
    //Pela própria classe.
    //Por classes do mesmo package.
    //Por subclasses (classes filhas), mesmo que estejam em outro package.

    //d) public
    //Um atributo ou método public pode ser acessado de qualquer lugar do programa.




}
